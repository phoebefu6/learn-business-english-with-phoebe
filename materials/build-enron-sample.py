"""build-enron-sample.py - the real-email base for the plain-English bench.

Source: the CMU Enron Email Dataset, release of 7 May 2015 (William W. Cohen, CMU;
https://www.cs.cmu.edu/~enron/). Public; released by the US Federal Energy Regulatory
Commission during its investigation. Only SENT folders are read, so every message was written
by the mailbox owner, and only the text the sender typed is kept.

Run:
  curl -s https://www.cs.cmu.edu/~enron/enron_mail_20150507.tar.gz | tar xzf - \
       --include='maildir/*/sent_items/*' --include='maildir/*/_sent_mail/*' --include='maildir/*/sent/*'
  python3 materials/build-enron-sample.py <path to maildir>

What it does, in order:
  1. parse every sent message, keep the body only (no headers, no names from headers);
  2. cut quoted replies and forwards at the first marker (Original Message, Forwarded by,
     a To:/From:/cc: line, a "wrote:" line, a ">" quote);
  3. keep English business prose of 40 to 250 words with no HTML, drop obviously personal mail;
  4. drop exact duplicates (the same message sits in sent and _sent_mail);
  5. mask every run of 6+ digits, every phone-shaped number and every email address;
  6. draw 400 with random.Random(20261006) and write assets/plain-sample.js with json.dumps.
"""
from __future__ import annotations

import email
import hashlib
import json
import random
import re
import sys
from email import policy
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import plain_reference as pr  # noqa: E402

SEED, N = 20261006, 400
CUT = re.compile(
    r"-{2,}\s*Original Message|-{2,}\s*Forwarded by|^\s*From:\s|^\s*To:\s|^\s*cc:\s|^\s*Sent:\s"
    r"|^\s*Subject:\s|wrote:\s*$|^\s*>|^\s*\S+@\S+\s+on\s+\d|^\s*\S+@(?:ECT|ENRON|EES|ENRONXGATE)\b",
    re.I | re.M,
)
DATELINE = re.compile(r"^\s*\d{1,2}/\d{1,2}/\d{2,4}\s+\d{1,2}:\d{2}\s*[AP]M", re.M)
PERSONAL = re.compile(
    r"\b(ass|damn|hell|shit|fuck\w*|crap|wife|husband|baby|love you|honey|sweetie|doctor|hospital|church|wedding|divorce|sex|drunk|"
    r"beer|girlfriend|boyfriend|mom|dad|kids|funeral|pregnant|son|daughter|girls|boys|children|family|vacation|birthday)\b", re.I)


def body_of(path: Path) -> str | None:
    try:
        msg = email.message_from_bytes(path.read_bytes(), policy=policy.compat32)
    except Exception:
        return None
    if msg.is_multipart():
        return None
    try:
        text = msg.get_payload(decode=True).decode("latin-1")
    except Exception:
        return None
    m = CUT.search(text)
    if m:
        text = text[: m.start()]
    d = DATELINE.search(text)
    if d:  # a Lotus Notes reply header: cut from the start of its block (the name lines above it)
        head = text[: d.start()]
        k = max(head.rfind("\n\n"), head.rfind("\n \n"))
        text = head[:k] if k > 0 else head
    return text.strip()


def mask(text: str) -> str:
    text = re.sub(r"[^\s@]+@\S*|@[A-Za-z]\S*", "[email]", text)
    text = re.sub(r"\(?\b\d{3}\)?[-. ]\d{3}[-. ]\d{4}\b", "[phone]", text)
    text = re.sub(r"\b\d{3}[-.]\d{4}\b", "[phone]", text)
    text = re.sub(r"\d{6,}", lambda m: "#" * len(m.group(0)), text)
    return text


def keep(text: str) -> bool:
    if not text or "<" in text and ">" in text:
        return False
    n = len(pr.words(pr.normalise(text)))
    if n < 40 or n > 250:
        return False
    letters = sum(c.isalpha() for c in text)
    if letters < 0.6 * len(text.replace(" ", "").replace("\n", "")):
        return False
    if PERSONAL.search(text):
        return False
    return True


def main(maildir: str) -> None:
    root = Path(maildir)
    seen, pool, scanned, owners = set(), [], 0, set()
    for f in sorted(root.glob("*/*/*")):
        if not f.is_file() or f.parent.name not in ("sent", "sent_items", "_sent_mail"):
            continue
        scanned += 1
        b = body_of(f)
        if not b or not keep(b):
            continue
        b = mask(re.sub(r"[ \t]+\n", "\n", b))
        h = hashlib.sha1(re.sub(r"\s+", " ", b.lower()).encode()).hexdigest()
        if h in seen:
            continue
        seen.add(h)
        pool.append(b)
        owners.add(f.parent.parent.name)
    rnd = random.Random(SEED)
    sample = rnd.sample(pool, N)
    meta = {
        "source": "CMU Enron Email Dataset, 7 May 2015 release, sent folders only",
        "scanned": scanned, "eligible": len(pool), "mailboxes": len(owners), "n": N, "seed": SEED,
        "rule": "own text only, 40 to 250 words, quoted replies cut, 6+ digit runs, phones and emails masked",
    }
    out = HERE.parent / "assets" / "plain-sample.js"
    out.write_text(
        "/* plain-sample.js - 400 real business emails from the public CMU Enron corpus.\n"
        " * Generated by materials/build-enron-sample.py with json.dumps. Do not edit by hand. */\n"
        "var PLAIN_SAMPLE = " + json.dumps({"meta": meta, "emails": sample}, ensure_ascii=True) + ";\n"
        "if (typeof window !== \"undefined\") window.PLAIN_SAMPLE = PLAIN_SAMPLE;\n"
        "if (typeof module !== \"undefined\") module.exports = PLAIN_SAMPLE;\n"
    )
    print(json.dumps(meta, indent=1), out.stat().st_size, "bytes")


if __name__ == "__main__":
    main(sys.argv[1])
