"""build-ladder.py - writes assets/plain-ladder.js from materials/ladder.json with json.dumps.

The ladder is CONSTRUCTED: one stiff email by Mei Lin Goh, a constructed analyst in Singapore,
rewritten one habit at a time, plus the anti-lever "sound more formal". Edit ladder.json, re-run.
"""
import json
from pathlib import Path

here = Path(__file__).resolve().parent
rungs = json.loads((here / "ladder.json").read_text())
data = [{"id": "r%d" % i, "label": r[0], "text": r[1], "anti": r[0].startswith("Anti")} for i, r in enumerate(rungs)]
(here.parent / "assets" / "plain-ladder.js").write_text(
    "/* plain-ladder.js - the constructed ladder for the plain-English bench. Generated by\n"
    " * materials/build-ladder.py from materials/ladder.json. Do not edit by hand. */\n"
    "var PLAIN_LADDER = " + json.dumps(data, ensure_ascii=True, indent=1) + ";\n"
    "if (typeof window !== \"undefined\") window.PLAIN_LADDER = PLAIN_LADDER;\n"
    "if (typeof module !== \"undefined\") module.exports = PLAIN_LADDER;\n")
print(len(data), "rungs")
